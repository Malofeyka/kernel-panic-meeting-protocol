def main() -> None:
    for tool in ("say", "ffmpeg", "textutil"):
        if not shutil.which(tool):
            raise SystemExit(f"Нужен {tool} (скрипт рассчитан на macOS с ffmpeg)")
    OUT.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as t:
        audio = make_audio(Path(t))
    # Mock-слой проваливает обработку, если в имени аудио есть «fail»
    shutil.copy(audio, OUT / "fail — запись для проверки ошибки.m4a")
    # Неподдерживаемый формат (AIFF) — для проверки сообщения об ошибке
    run("say", "-v", "Milena", "-o", OUT / "Запись в неверном формате.aiff", "Проверка формата.")
    # Готовая стенограмма — вариант без распознавания речи (бэкенд без GigaAM)
    names = {
        "chair": "Председатель",
        "ivanov": "Иванов",
        "sidorov": "Сидоров",
        "morozov": "Морозов",
        "kuznetsova": "Кузнецова",
    }
    (OUT / "стенограмма").mkdir(exist_ok=True)
    (OUT / "стенограмма" / f"Стенограмма совещания {DATE}.txt").write_text(
        "\n".join(f"{names[who]}: {text}" for who, text in DIALOGUE), encoding="utf-8"
    )
    make_docs()
    for p in sorted(OUT.rglob("*")):
        print(p.relative_to(OUT))


if __name__ == "__main__":
    main()
