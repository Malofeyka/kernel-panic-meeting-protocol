def run(*cmd: str) -> None:
    subprocess.run(cmd, check=True, capture_output=True)


def make_audio(tmp: Path) -> Path:
    parts: list[Path] = []
    pause = tmp / "pause.wav"
    run("ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=22050:cl=mono", "-t", "0.7", pause)
    for i, (who, text) in enumerate(DIALOGUE):
        raw = tmp / f"{i:02}.aiff"
        run("say", "-v", "Milena", "-r", "170", "-o", raw, text)
        k = VOICES[who]
        wav = tmp / f"{i:02}.wav"
        # Тон ниже, темп прежний
        run(
            "ffmpeg",
            "-y",
            "-i",
            raw,
            "-af",
            f"asetrate=22050*{k},aresample=22050,atempo={1 / k:.4f}",
            "-ac",
            "1",
            wav,
        )
        parts += [wav, pause]

    listing = tmp / "list.txt"
    listing.write_text("".join(f"file '{p}'\n" for p in parts))
    out = OUT / f"Аппаратное совещание {DATE}.m4a"
    # Лёгкий шум помещения, чтобы запись не звучала «стерильно»
    run(
        "ffmpeg",
        "-y",
        "-f",
        "concat",
        "-safe",
        "0",
        "-i",
        listing,
        "-f",
        "lavfi",
        "-i",
        "anoisesrc=color=brown:amplitude=0.004:r=22050",
        "-filter_complex",
        "[0][1]amix=inputs=2:duration=first:normalize=0",
        "-c:a",
        "aac",
        "-b:a",
        "64k",
        out,
    )
    return out


def docx(name: str, body: str) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False, encoding="utf-8") as f:
        f.write(
            f'<html><head><meta charset="utf-8"></head>'
            f'<body style="font-family: Times New Roman; font-size: 14pt">{body}</body></html>'
        )
    run(
        "textutil",
        "-convert",
        "docx",
        "-inputencoding",
        "UTF-8",
        "-output",
        str(OUT / name),
        f.name,
    )
    Path(f.name).unlink()


def table(rows: list[tuple[str, ...]], head: tuple[str, ...]) -> str:
    th = "".join(f"<th>{h}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table border="1" cellpadding="4" cellspacing="0"><tr>{th}</tr>{tr}</table>'


