/** Сегменты по предложениям; таймкоды — по длине текста, как у живой речи */
export function demoTranscript(source: string): MeetingTranscription {
  const segments: MeetingTranscription['segments'] = []
  let t = 0
  for (const replica of REPLICAS) {
    for (const sentence of replica.split(/(?<=[.?!])\s+/)) {
      const dur = Math.max(1.5, sentence.length / 14)
      segments.push({ start: round(t), end: round(t + dur), text: sentence })
      t += dur + 0.3
    }
    t += 0.7
  }
  return { model: 'e2e_rnnt', source, text: segments.map((s) => s.text).join(' '), segments }
}

const round = (n: number) => Math.round(n * 10) / 10

function sourceOf(transcript: MeetingTranscription, quote: string) {
  const seg = transcript.segments.find((s) => s.text.includes(quote) || quote.includes(s.text))
  return { source_start: seg?.start ?? null, source_end: seg?.end ?? null }
}

